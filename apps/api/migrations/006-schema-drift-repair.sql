-- customer_status mirrors the existing boolean flags on first fill.
UPDATE customers
   SET customer_status = CASE
         WHEN is_blocked THEN 'blocked'
         WHEN is_active  THEN 'active'
         ELSE 'inactive'
       END
 WHERE customer_status IS NULL OR customer_status = 'active';

-- Audit rows written before admin_id existed keep their author.
UPDATE admin_audit_logs SET admin_id = user_id WHERE admin_id IS NULL;

-- delivery_run_addresses gained a parallel status/sequence pair.
UPDATE delivery_run_addresses
   SET status = COALESCE(status, delivery_status, 'pending'),
       sequence_number = COALESCE(NULLIF(sequence_number, 0), sequence_no, 0);

-- delivery_runs.run_number defaults to the human-facing run id.
UPDATE delivery_runs SET run_number = run_id WHERE run_number IS NULL;

-- Identity columns on customers/delivery_partners mirror `users`. They are
-- plain columns (not generated) because they cross tables, so a trigger keeps
-- them in step with the source of truth.
CREATE OR REPLACE FUNCTION sync_profile_from_users() RETURNS trigger AS $$
BEGIN
  UPDATE customers
     SET first_name = NEW.first_name,
         last_name  = NEW.last_name,
         phone      = NEW.phone,
         email      = NEW.email
   WHERE customer_id = NEW.user_id;

  UPDATE delivery_partners
     SET user_id   = NEW.user_id,
         full_name = NULLIF(TRIM(COALESCE(NEW.first_name, '') || ' ' || COALESCE(NEW.last_name, '')), ''),
         phone     = NEW.phone,
         email     = NEW.email
   WHERE delivery_partner_id = NEW.user_id;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_profile_sync ON users;
CREATE TRIGGER users_profile_sync
  AFTER INSERT OR UPDATE OF first_name, last_name, phone, email ON users
  FOR EACH ROW EXECUTE FUNCTION sync_profile_from_users();

UPDATE customers c
   SET first_name = u.first_name,
       last_name  = u.last_name,
       phone      = u.phone,
       email      = u.email
  FROM users u
 WHERE u.user_id = c.customer_id;

UPDATE delivery_partners dp
   SET user_id   = u.user_id,
       full_name = NULLIF(TRIM(COALESCE(u.first_name, '') || ' ' || COALESCE(u.last_name, '')), ''),
       phone     = u.phone,
       email     = u.email
  FROM users u
 WHERE u.user_id = dp.delivery_partner_id;

